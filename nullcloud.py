CIDR_RE = re.compile(r"\b(?:(?:25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\.){3}(?:25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)/(?:3[0-2]|[1-2][0-9]|[0-9])\b")


def extract_ips(text: str) -> list[str]:
    return list(set(IP_RE.findall(text)))


def extract_cidrs(text: str) -> list[str]:
    return list(set(CIDR_RE.findall(text)))


