def fetch_dnsdumpster(domain: str, timeout: int = 10) -> set[tuple[str, str]]:
    try:
        base = "https://dnsdumpster.com/"
        req = urllib.request.Request(base, headers={"User-Agent": "NullCloud/1.0"})
        resp = urllib.request.urlopen(req, timeout=timeout).read().decode()
        csrf_match = re.search(r'name="csrfmiddlewaretoken"[^>]*value="([^"]+)"', resp)
        if not csrf_match:
            csrf_match = re.search(r'value="([^"]+)"[^>]*name="csrfmiddlewaretoken"', resp)
        if not csrf_match:
            return set()
        csrf = csrf_match.group(1)
        data = urllib.parse.urlencode({"csrfmiddlewaretoken": csrf, "targetip": domain}).encode()
        req = urllib.request.Request(base, data=data, method="POST", headers={
            "User-Agent": "NullCloud/1.0",
            "Referer": base,
            "Content-Type": "application/x-www-form-urlencoded",
        })
        resp = urllib.request.urlopen(req, timeout=timeout).read().decode()
        results = set()
        if HAVE_BS4:
            soup = BeautifulSoup(resp, "html.parser")
            for table in soup.find_all("table"):
                for row in table.find_all("tr"):
                    cols = row.find_all("td")
                    if len(cols) >= 2:
                        sub = re.sub(r"\s+", " ", cols[0].get_text(" ", strip=True)).lower()
                        ip = re.sub(r"\s+", " ", cols[1].get_text(" ", strip=True))
                        if sub.endswith(f".{domain}") or sub == domain:
                            for addr in IP_RE.findall(ip):
                                results.add((sub, addr))
        return results
    except Exception:
        return set()


def fetch_favicon_hash(domain: str, timeout: int = 10) -> dict:
    result = {}
