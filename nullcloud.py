def get_provider_ranges(name: str, timeout: int = 10) -> tuple[list, list]:
    provider = PROVIDERS[name]
    fetch = provider.get("fetch")
    fetched_v4 = []
    fetched_v6 = []
    if fetch:
        try:
            fetched_v4, fetched_v6 = fetch(timeout)
        except Exception:
            pass
    ipv4 = []
    seen_v4 = set()
    for net in fetched_v4:
        s = str(net)
        if s not in seen_v4:
            seen_v4.add(s)
            ipv4.append(net)
    for item in provider.get("fallback_ipv4", []):
        try:
            net = ipaddress.ip_network(item)
            s = str(net)
            if s not in seen_v4:
                seen_v4.add(s)
                ipv4.append(net)
        except Exception:
            pass
    ipv6 = []
    seen_v6 = set()
    for net in fetched_v6:
        s = str(net)
        if s not in seen_v6:
            seen_v6.add(s)
            ipv6.append(net)
    for item in provider.get("fallback_ipv6", []):
        try:
            net = ipaddress.ip_network(item)
            s = str(net)
            if s not in seen_v6:
                seen_v6.add(s)
                ipv6.append(net)
        except Exception:
            pass
    return ipv4, ipv6


def build_network_map(provider_names: list[str], timeout: int = 10) -> list:
    network_map = []
    for name in provider_names:
        ipv4_ranges, ipv6_ranges = get_provider_ranges(name, timeout)
        for net in ipv4_ranges + ipv6_ranges:
            network_map.append((net, name))
    return network_map


def classify_ip(ip: str, network_map: list) -> Optional[str]:
    try:
        addr = ipaddress.ip_address(ip)
    except ValueError:
        return None
    for net, provider in network_map:
        if addr in net:
            return provider
    return None


def resolve_records(subdomain: str, record_type: str) -> list[str]:
    if HAVE_DNS:
        try:
            answers = dns.resolver.resolve(subdomain, record_type)
            return [str(rdata) for rdata in answers]
        except Exception:
            return []
    try:
        if record_type == "A":
            return list(set(socket.gethostbyname_ex(subdomain)[2]))
        if record_type == "AAAA":
            results = []
            for _, _, _, _, sockaddr in socket.getaddrinfo(subdomain, None, socket.AF_INET6):
                results.append(sockaddr[0])
            return list(set(results))
    except Exception:
        return []
    return []


