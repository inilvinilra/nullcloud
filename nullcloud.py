def follow_cname(domain: str, timeout: int = 10) -> list[str]:
    chain = []
    current = domain
    for _ in range(10):
        records = resolve_records(current, "CNAME")
        if not records:
            break
        nxt = records[0].rstrip(".")
        chain.append(nxt)
        current = nxt
    return chain


