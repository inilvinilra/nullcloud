def print_normal(results: list[dict], quiet: bool, verbose: bool, origins: Optional[dict] = None, network_map: Optional[list] = None) -> None:
    for item in results:
        if item["status"] == "not_found":
            if verbose:
                print(f"[-] {item['subdomain']} -> not found")
            continue
        if item["ips"]:
            print(f"[+] {item['subdomain']} -> real: {', '.join(item['ips'])}")
        if item["protected"]:
            if not quiet:
                grouped = {}
                for entry in item["protected"]:
                    grouped.setdefault(entry["service"], []).append(entry["ip"])
                for service in sorted(grouped):
                    print(f"[!] {item['subdomain']} -> {service}: {', '.join(grouped[service])}")
        if not item["ips"] and not item["protected"] and verbose:
            print(f"[-] {item['subdomain']} -> no records")
    if origins:
        print(f"\n[*] Origin reconnaissance for {origins['domain']}")
        if origins["cname_chain"]:
            print(f"[cname] {' -> '.join(origins['cname_chain'])}")
        if origins["backend"]:
            print(f"[backend] {origins['backend']}")
        if origins["favicon_hash"]:
            for key, value in origins["favicon_hash"].items():
                print(f"[favicon] {key}: {value}")
        if origins["mx_hosts"]:
            for mx in origins["mx_hosts"]:
                print(f"[mx] {mx}")
        if origins["txt_records"]:
            for txt in origins["txt_records"]:
                print(f"[txt] {txt}")
        if origins["ptr_hints"]:
            for hint in origins["ptr_hints"]:
                print(f"[ptr] {hint['ip']} -> {hint['ptr']}")
        if origins["header_leaks"]:
            for leak in origins["header_leaks"]:
                ip = leak.get("ip") or "n/a"
                print(f"[header] {leak['header']}: {ip} ({leak['raw'][:80]})")
        for key in ("hackertarget_pairs", "rapiddns_pairs", "dnsdumpster_pairs", "fofa_pairs", "shodan_pairs", "censys_pairs", "netlas_pairs", "criminalip_pairs"):
            if origins[key]:
                print(f"\n[*] {key} ({len(origins[key])} entries)")
                for entry in origins[key][:20]:
                    status = "origin" if (network_map and not classify_ip(entry["ip"], network_map)) else "protected"
                    print(f"  {entry['subdomain']:<50} {entry['ip']:<40} {status}")
        if origins["external_subdomains"]:
            external_found = sum(1 for sub in origins["external_subdomains"] if sub != origins["domain"])
            if external_found:
                print(f"\n[*] External subdomain sources: {external_found} unique subdomains")
        if origins["origin_ips"]:
            for entry in origins["origin_ips"]:
                print(f"[origin] {entry['ip']} ({entry['source']}, subdomain: {entry['subdomain']})")
        if origins["origin_ranges"]:
            for entry in origins["origin_ranges"]:
                print(f"[range] {entry['range']} ({entry['source']})")
        if origins["axfr_subdomains"]:
            for sub in origins["axfr_subdomains"][:20]:
                print(f"[axfr] {sub}")
        if origins.get("asnsweep"):
            sweep = origins["asnsweep"]
            if sweep.get("candidates"):
                print(f"\n[*] ASN sweep candidates ({len(sweep['candidates'])})")
                for cand in sweep["candidates"][:20]:
                    print(f"  {cand['ip']:<40} confidence={cand.get('confidence')} reasons={cand.get('match_reasons')}")
        if origins.get("bodyfingerprint"):
            body = origins["bodyfingerprint"]
            if body.get("candidates"):
                print(f"\n[*] Body fingerprint candidates ({len(body['candidates'])})")
                for cand in body["candidates"][:20]:
                    print(f"  {cand['ip']:<40} confidence={cand.get('confidence')} reasons={cand.get('match_reasons')}")
        if origins.get("cloudstorage"):
            storage = origins["cloudstorage"]
            if storage.get("found"):
                print(f"\n[*] Cloud storage findings ({len(storage['found'])})")
                for entry in storage["found"][:20]:
                    print(f"  {entry['url']:<70} status={entry.get('status')}")
        has_any = any(origins[k] for k in origins if k not in ("domain", "favicon_hash"))
        if not has_any and not origins["favicon_hash"]:
            print("[-] No origin candidates found")


def output_json(results: list[dict], file_object, origins: Optional[dict] = None) -> None:
    payload = {"results": results}
    if origins:
        payload["origins"] = origins
    json.dump(payload, file_object, indent=2)


def output_yaml(results: list[dict], file_object, origins: Optional[dict] = None) -> None:
    if not HAVE_YAML:
        raise RuntimeError("PyYAML is required for YAML output")
    payload = {"results": results}
    if origins:
        payload["origins"] = origins
    yaml.dump(payload, file_object, default_flow_style=False)


def output_csv(results: list[dict], file_object, origins: Optional[dict] = None) -> None:
    writer = csv.writer(file_object)
    writer.writerow(["subdomain", "ip", "type", "service"])
    for item in results:
        for ip in item["ips"]:
            writer.writerow([item["subdomain"], ip, "real", ""])
        for entry in item["protected"]:
            writer.writerow([item["subdomain"], entry["ip"], "protected", entry["service"]])
    if origins:
        for entry in origins.get("origin_ips", []):
            writer.writerow([entry["subdomain"], entry["ip"], "origin", entry["source"]])
        for entry in origins.get("origin_ranges", []):
            writer.writerow(["", entry["range"], "origin_range", entry["source"]])


def list_services() -> None:
    print("Supported services:")
    for key in sorted(PROVIDERS):
        print(f"  {key:<15} {PROVIDERS[key]['label']}")


def main() -> None:
    args = parse_args()
    if args.list_services:
        list_services()
        return
    if not args.domain:
        print("[!] Target domain is required", file=sys.stderr)
        sys.exit(1)
    domain = args.domain.strip().lower()
    if domain.startswith("*."):
        domain = domain[2:]
    selected = args.service or list(PROVIDERS.keys())
    wordlists = args.wordlist or ["wordlist.txt"]
    if not HAVE_DNS:
        print("[!] dnspython not installed, falling back to socket resolver", file=sys.stderr)
    network_map = build_network_map(selected)
    words = load_wordlists(wordlists)
    if not words:
        print("[!] No words loaded from wordlists", file=sys.stderr)
        sys.exit(1)
    subdomains = build_subdomains(domain, words)
    results = []
    total = len(subdomains)
    real_count = 0
    protected_count = 0
    if args.rate and args.rate > 0:
        delay = 1.0 / args.rate
    else:
        delay = 0.0

    def worker(sub: str) -> dict:
        if delay:
            time.sleep(delay)
        return resolve_subdomain(sub, network_map)

    with ThreadPoolExecutor(max_workers=args.threads) as executor:
        futures = {executor.submit(worker, sub): sub for sub in subdomains}
        if HAVE_TQDM and not args.quiet:
            iterator = tqdm(as_completed(futures), total=total, desc="Scanning", unit="sub")
        else:
            iterator = as_completed(futures)
        for future in iterator:
            try:
                result = future.result()
            except Exception:
                continue
            results.append(result)
            if result["status"] == "found":
                if result["ips"]:
                    real_count += 1
                if result["protected"]:
                    protected_count += 1
            if HAVE_TQDM and not args.quiet and hasattr(iterator, "set_postfix"):
                iterator.set_postfix(real=real_count, protected=protected_count)
    results.sort(key=lambda x: x["subdomain"])
    origins = None
    keys = {}
    if args.origin or args.origin_active:
        key_path = args.origin_key_file or os.path.expanduser("~/.nullcloud/keys.yaml")
        keys = load_keys(key_path)

    if args.origin:
        if not args.quiet and args.format == "normal":
            print("\n[*] Running origin detection...")
        use_api = not args.origin_no_api
        origins = find_origins(domain, network_map, args.origin_timeout, keys=keys, use_api=use_api)
        if origins.get("origin_ips"):
            real_count += len(origins["origin_ips"])
        if args.origin_active and HAVE_RECON:
            if not args.quiet and args.format == "normal":
                print("[*] Running active origin reconnaissance...")
            modules = args.origin_module or ["asn", "cloud", "body"]
            seed_ips = [entry["ip"] for entry in origins.get("origin_ips", [])]
            config = {
                "timeout": args.origin_timeout,
                "active_timeout": args.origin_active_timeout,
                "threads": args.origin_active_threads,
                "sample": args.origin_sample,
                "max_ips": 256,
                "max_prefixes": 50,
                "seed_ips": seed_ips,
                "keys": keys,
            }
            active_results = recon.run_modules(modules, domain, network_map, config)
            for module_name, module_data in active_results.items():
                origins[module_name] = module_data
                for candidate in module_data.get("candidates", []):
                    ip = candidate.get("ip")
                    if ip and ip not in {entry["ip"] for entry in origins["origin_ips"]}:
                        origins["origin_ips"].append({"subdomain": domain, "ip": ip, "source": module_name})
                        real_count += 1
    if not args.quiet and args.format == "normal":
        print(f"\n[*] Scan complete: {real_count} real IP(s), {protected_count} protected IP(s) found\n")
    if args.report_format and HAVE_REPORTING:
        report = reporting.generate_report(results, origins or {"domain": domain}, args.report_format)
        if args.report_output:
            with open(args.report_output, "w", encoding="utf-8") as f:
                f.write(report)
            if not args.quiet:
                print(f"[*] Report saved to {args.report_output}")
        elif not args.quiet:
            print(report)
    if args.format == "normal":
        print_normal(results, args.quiet, args.verbose, origins, network_map)
    elif args.format == "json":
        if args.output:
            with open(args.output, "w", encoding="utf-8") as f:
                output_json(results, f, origins)
        else:
            output_json(results, sys.stdout, origins)
            print()
    elif args.format == "yaml":
        if not HAVE_YAML:
            print("[!] PyYAML is required for YAML output", file=sys.stderr)
            sys.exit(1)
        if args.output:
            with open(args.output, "w", encoding="utf-8") as f:
                output_yaml(results, f, origins)
        else:
            output_yaml(results, sys.stdout, origins)
    elif args.format == "csv":
        if args.output:
            with open(args.output, "w", newline="", encoding="utf-8") as f:
                output_csv(results, f, origins)
        else:
            buffer = io.StringIO()
            output_csv(results, buffer, origins)
            print(buffer.getvalue().rstrip("\r\n"))


if __name__ == "__main__":
    main()
