def http_get(url: str, timeout: int = 10) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "NullCloud/1.0", "Accept": "application/json"})
    return urllib.request.urlopen(req, timeout=timeout).read().decode()


def fetch_cloudflare(timeout: int = 10) -> tuple[list, list]:
    ipv4 = []
    ipv6 = []
    try:
        response = http_get("https://www.cloudflare.com/ips-v4", timeout)
        for line in response.splitlines():
            line = line.strip()
            if line:
                ipv4.append(ipaddress.ip_network(line))
    except Exception:
        return [], []
    try:
        response = http_get("https://www.cloudflare.com/ips-v6", timeout)
        for line in response.splitlines():
            line = line.strip()
            if line:
                ipv6.append(ipaddress.ip_network(line))
    except Exception:
        return ipv4, []
    return ipv4, ipv6


