def fetch_azure(timeout: int = 10) -> tuple[list, list]:
    base = "https://download.microsoft.com/download/7/1/D/71D86715-5596-4529-9B13-DA13A5DE5B63/ServiceTags_Public_{}.json"
    today = datetime.date.today()
    tags = {"AzureFrontDoor.Backend", "AzureFrontDoor.Frontend", "AzureFrontDoor.FirstParty"}
    for offset in range(14):
        date_str = (today - datetime.timedelta(days=offset)).strftime("%Y%m%d")
        try:
            data = json.loads(http_get(base.format(date_str), timeout))
            ipv4 = []
            ipv6 = []
            for entry in data.get("values", []):
                if entry.get("name") not in tags:
                    continue
                for prefix in entry.get("properties", {}).get("addressPrefixes", []):
                    try:
                        net = ipaddress.ip_network(prefix)
                        if isinstance(net, ipaddress.IPv4Network):
                            ipv4.append(net)
                        else:
                            ipv6.append(net)
                    except Exception:
                        pass
            return ipv4, ipv6
        except Exception:
            continue
    return [], []


